"""Extract the two mainland rings and the search extent for paired border labels."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts/world/lib"))
import shapefile

source = ROOT / "scripts/world"
polygons = {}
for item in shapefile.Reader(str(source / "countries.zip")).iterShapeRecords():
    country = item.record["ADM0_A3"]
    if country in {"ESP", "PRT"}:
        starts = [*item.shape.parts, len(item.shape.points)]
        rings = [item.shape.points[a:b] for a, b in zip(starts, starts[1:])]
        def area(ring):
            return abs(sum(a[0]*b[1] - b[0]*a[1] for a, b in zip(ring, ring[1:])))
        polygons[country] = [[round(x, 4), round(y, 4)] for x, y in max(rings, key=area)]
assert set(polygons) == {"ESP", "PRT"}
