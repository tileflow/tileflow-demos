assert bounds[0] < -8 and bounds[1] < 37.5 and bounds[3] > 42
target = ROOT / "public/detail/iberia-border-rings.mjs"
def js(v):
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))
target.write_text("// Natural Earth, public domain. Generated by make-border-countries.py.\n"
                  + f"export const borderBounds={js(bounds)};\n"
                  + f"export const portugal={js(polygons['PRT'])};\n"
                  + f"export const spain={js(polygons['ESP'])};\n")
