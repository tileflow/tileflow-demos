import assert from 'node:assert/strict';
import {viewport,toGeometry,intersects} from './geometry.mjs';
import {normalizeProperties} from './layers.mjs';

const v=viewport([178,-3,-177,3],4);
assert.ok(v.tiles.some(t=>t.x===0) && v.tiles.some(t=>t.x===15));
assert.equal(new Set(v.tiles.map(t=>t.key)).size,v.tiles.length);
assert.ok(intersects([-180,-1,-179,1],v));
assert.ok(!intersects([0,0,1,1],v));
assert.deepEqual(viewport([178,-3,183,3],4).tiles,v.tiles);
const whole=viewport([-180,-90,180,90],20);
assert.ok(whole.tiles.length<=32);
assert.equal(viewport([3,3,3.001,3.001],20).z,15);
const tile={x:0,y:0,z:0},e=100;
const line=toGeometry({type:'LineString',geometry:[[-10,50,50,50,120,50,120,0,50,50]]},tile,e);
assert.equal(line.geometry.type,'MultiLineString');
assert.equal(line.geometry.coordinates[0][0][0],-180);
assert.equal(line.geometry.coordinates[0].at(-1)[0],180);
const poly=toGeometry({type:'Polygon',geometry:[[0,0,50,0,50,50,0,50,0,0],[5,5,5,10,10,10,10,5,5,5],[60,60,70,60,70,70,60,70,60,60]]},tile,e);
assert.equal(poly.geometry.type,'MultiPolygon');
assert.equal(poly.geometry.coordinates[0].length,2);
const points=toGeometry({type:'Point',geometry:[[-5,20,30,50,100,60]]},tile,e);
assert.equal(points.geometry.type,'Point');
assert.equal(normalizeProperties('natural_label',{class:'ocean',name:'Atlantic'},'1/1/1',7)._layer,'water_name');
assert.equal(normalizeProperties('place_label',{class:'settlement',type:'city'},'1/1/1').class,'city');
console.log('Passed canonical antimeridian cover, bounds, overzoom, tile cap, clipped line, polygon holes, multipolygon, points and labels.');
const {inheritedOcean}=await import('./geometry.mjs');
const oceanTile={z:3,x:4,y:3,key:'3/4/3'};
const outer=[[-12,-10],[60,-10],[60,50],[-12,50],[-12,-10]];
const sea=(rings,type='ocean')=>[{type:'Feature',properties:{_layer:'water',class:type},geometry:{type:'Polygon',coordinates:rings}}];
assert.equal(inheritedOcean(oceanTile,sea([outer])).properties.class,'ocean');
assert.equal(inheritedOcean(oceanTile,sea([outer], 'lake')),null);
assert.equal(inheritedOcean(oceanTile,sea([outer,[[1,1],[1,2],[2,2],[2,1],[1,1]]])),null);
assert.equal(inheritedOcean(oceanTile,[]),null);
console.log('Passed sparse child ocean: confirmed parent, island hole, non-ocean lake, interior desert.');
