// Bake the local font-faces glyphs with the TinySDF options and metrics of the installed MapLibre.
import {createRequire} from 'node:module';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {launch} from '../qa/browser.mjs';
const output=resolve('public/detail');
const require=createRequire(import.meta.url);
const sdk=createRequire(require.resolve('maplibre-gl'));
const tiny=await readFile(sdk.resolve('@mapbox/tiny-sdf'));
const font=await readFile(resolve(output,'../fonts/jetbrains-mono.woff2'));
const browser=await launch();
try{
  const page=await browser.newPage();
  const result=await page.evaluate(async ({code,font})=>{
    const family='AtlasJetBrainsMono';
    document.fonts.add(await new FontFace(family,'url(data:font/woff2;base64,'+font+')').load());
    const {default:TinySDF}=await import('data:text/javascript;base64,'+code);
    const sdf=new TinySDF({fontSize:48,buffer:6,radius:16,cutoff:.25,fontFamily:family});
    const chars=[...'~·:′∧^–-═━,'];
    const width=256,height=128,pixels=new Uint8Array(width*height),metrics={};
    let x=1,y=1,row=0;
    for(const glyph of chars){
      const g=sdf.draw(glyph);
      if(x+g.width+2>width){x=1;y+=row+2;row=0;}
      if(y+g.height+2>height)throw Error('Glyph atlas overflow');
      for(let j=0;j<g.height;j++)pixels.set(g.data.subarray(j*g.width,(j+1)*g.width),(y+j)*width+x);
      // MapLibre puts one transparent pixel around the SDF cell. Its normalized
      // metrics include the same +0.5 left, -27.5 baseline and -17 shaping shift.
      const left=g.glyphLeft/2+.5-4-g.glyphAdvance/4;
      const top=-g.glyphTop/2+27.5-4-17-.13*24;
      metrics[glyph]={rect:[left,top,(g.width+2)/2,(g.height+2)/2],uv:[x-1,y-1,g.width+2,g.height+2]};
      x+=g.width+2;row=Math.max(row,g.height);
    }
    return {width,height,metrics,bytes:[...pixels]};
  },{code:tiny.toString('base64'),font:font.toString('base64')});
  const {width,height,metrics,bytes}=result;
  await writeFile(output+'/glyph-atlas.bin',Buffer.from(bytes));
  await writeFile(output+'/glyph-metrics.mjs','// Generated by scripts/visor-dev/build-glyph-atlas.mjs using the map’s local font.\nexport const atlas='+JSON.stringify({width,height,metrics})+';\n');
  console.log(Object.keys(metrics).join(''),width,height,bytes.length);
}finally{await browser.close();}
